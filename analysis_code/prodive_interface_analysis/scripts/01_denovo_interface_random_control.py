def main():
    args = parse_args()
    apply_args(args)

    for p in [HIT_CSV, FASTA]:
        if not os.path.exists(p):
            print(f"❌ File not found: {p}", file=sys.stderr)
            sys.exit(1)
    if not os.path.isdir(STRUCT_DIR):
        print(f"❌ STRUCT_DIR not found: {STRUCT_DIR}", file=sys.stderr)
        sys.exit(1)

    print("[INFO] Loading FASTA...")
    fasta_dict = load_fasta_dict(FASTA)
    print(f"[INFO] FASTA sequences: {len(fasta_dict)}")

    print("[INFO] Reading hit CSV...")
    df = pd.read_csv(HIT_CSV, low_memory=False)
    need_cols = ["Main_HMM", "Main_Segment"]
    for c in need_cols:
        if c not in df.columns:
            print(f"❌ CSV missing required column: {c}", file=sys.stderr)
            print("   Found columns:", list(df.columns), file=sys.stderr)
            sys.exit(1)

    groups = [(k, g.copy()) for k, g in df.groupby("Main_HMM", sort=False)]
    print(f"[INFO] Main_HMM groups: {len(groups)}")

    workers = min(MAX_WORKERS, os.cpu_count() or 1)
    print(f"[INFO] Using workers={workers}")

    outs = []
    logs = []

    with ProcessPoolExecutor(max_workers=workers, initializer=_init_worker, initargs=(_runtime_config_dict(),)) as ex:
        futures = [ex.submit(process_one_main_hmm_task, k, g, fasta_dict, STRUCT_DIR) for k, g in groups]

        iterator = as_completed(futures)
        if tqdm is not None:
            iterator = tqdm(iterator, total=len(futures), desc="Processing Main_HMM", unit="grp")

        for fut in iterator:
            try:
                main_hmm, out_sub, msg = fut.result()
                outs.append(out_sub)
                logs.append(msg)
            except Exception as e:
                logs.append(f"[FUTURE_ERROR] {type(e).__name__}: {e}")

    print("\n[INFO] Sample logs:")
    for s in logs[:10]:
        print("  ", s)

    out_df = pd.concat(outs, ignore_index=True)
    print(f"\n[INFO] Writing output CSV: {OUT_CSV}")
    out_dir = os.path.dirname(os.path.abspath(OUT_CSV))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    out_df.to_csv(OUT_CSV, index=False)

    if "FragmentInterfaceClass" in out_df.columns:
        print("\n[SUMMARY] FragmentInterfaceClass counts:")
        print(out_df["FragmentInterfaceClass"].value_counts(dropna=False).head(30))

    if "AssemblyNeedSymGen" in out_df.columns:
        print("\n[SUMMARY] AssemblyNeedSymGen counts:")
        print(out_df["AssemblyNeedSymGen"].value_counts(dropna=False))

    print("\n[DONE]")


if __name__ == "__main__":
    main()
