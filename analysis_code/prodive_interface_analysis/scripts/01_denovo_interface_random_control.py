# Worker: per Main_HMM group
# ============================================================
def process_one_main_hmm_task(main_hmm: str, sub_df: pd.DataFrame, fasta_dict: Dict[str, Tuple[str, str]],
                             struct_dir: str) -> Tuple[str, pd.DataFrame, str]:
    aligner = build_aligner()
    pdb_id = main_hmm_to_pdbid(main_hmm)

    # local RNG per worker & per group (reproducible but different groups different stream)
    # use hash(main_hmm) to decorrelate
    seed = (RAND_SEED ^ (hash(main_hmm) & 0xFFFFFFFF)) & 0xFFFFFFFF
    rng = np.random.default_rng(seed)

    if main_hmm not in fasta_dict:
        out = sub_df.copy()
        out["pdb_id"] = pdb_id
        out["AssemblyClass"] = "NO_FASTA"
        out["FragmentInterfaceClass"] = "NA"
        out["warn"] = "NO_FASTA_ID"
        # random columns
        out["rand_samples"] = RAND_SAMPLES
        out["rand_mean_interface_frac"] = np.nan
        out["rand_std_interface_frac"] = np.nan
        out["interface_fraction_real"] = np.nan
        out["rand_zscore"] = np.nan
        out["rand_pvalue_ge"] = np.nan
        out["rand_enrichment"] = np.nan
        return main_hmm, out, f"[{main_hmm}] NO_FASTA_ID"

    fasta_seq, fasta_desc = fasta_dict[main_hmm]
    chain_candidates = extract_chain_candidates_from_desc(fasta_desc)

    cif_path, pdb_path = find_structure_file(pdb_id, struct_dir)
    st, used_path, mode = parse_structure_prefer_cif(cif_path, pdb_path)
    if st is None:
        out = sub_df.copy()
        out["pdb_id"] = pdb_id
        out["AssemblyClass"] = "NO_STRUCTURE"
        out["FragmentInterfaceClass"] = "NA"
        out["warn"] = "NO_STRUCTURE_FILE"
        out["rand_samples"] = RAND_SAMPLES
        out["rand_mean_interface_frac"] = np.nan
        out["rand_std_interface_frac"] = np.nan
        out["interface_fraction_real"] = np.nan
        out["rand_zscore"] = np.nan
        out["rand_pvalue_ge"] = np.nan
        out["rand_enrichment"] = np.nan
        return main_hmm, out, f"[{main_hmm}] NO_STRUCTURE_FILE"

    olig_count, need_symgen = ("NA", "unknown")
    if used_path and used_path.lower().endswith((".cif", ".mmcif")):
        olig_count, need_symgen = cif_assembly_need_symgen(used_path)

    model = next(st.get_models())
    prot_chains = list_protein_chains(model)
    n_prot = len(prot_chains)

    # fallback if desc has no chain info: use suffix _1/_2
    if not chain_candidates:
        m = re.search(r"_(\d+)$", str(main_hmm))
        if m and n_prot > 0:
            idx = int(m.group(1)) - 1
            if 0 <= idx < n_prot:
                chain_candidates = [prot_chains[idx].id]

    # choose best chain by alignment score
    best = None  # (score, chain_id, struct_seq, struct_keys, struct_residues)
    for ch in prot_chains:
        if chain_candidates and ch.id not in chain_candidates:
            continue
        residues, struct_seq, struct_keys = get_chain_std_residues_and_seq(ch)
        if len(struct_seq) < 5:
            continue
        score = global_align_score(aligner, fasta_seq, struct_seq)
        if score is None:
            continue
        if best is None or score > best[0]:
            best = (score, ch.id, struct_seq, struct_keys, residues)

    chain_id_mode = mode
    if best is None and mode == "mmcif_auth" and used_path and used_path.lower().endswith((".cif", ".mmcif")):
        try:
            st2 = parse_structure_mmcif_label(used_path)
            model2 = next(st2.get_models())
            prot_chains2 = list_protein_chains(model2)
            n_prot2 = len(prot_chains2)

            best2 = None
            for ch in prot_chains2:
                if chain_candidates and ch.id not in chain_candidates:
                    continue
                residues, struct_seq, struct_keys = get_chain_std_residues_and_seq(ch)
                if len(struct_seq) < 5:
                    continue
                score = global_align_score(aligner, fasta_seq, struct_seq)
                if score is None:
                    continue
                if best2 is None or score > best2[0]:
                    best2 = (score, ch.id, struct_seq, struct_keys, residues)

            if best2 is not None:
                st, model, prot_chains, n_prot, best = st2, model2, prot_chains2, n_prot2, best2
                chain_id_mode = "mmcif_label"
        except Exception:
            pass

    if best is None:
        out = sub_df.copy()
        out["pdb_id"] = pdb_id
        out["n_protein_chains"] = n_prot
        out["AssemblyNeedSymGen"] = need_symgen
        out["oligomeric_count_annot"] = olig_count
        out["AssemblyClass"] = "CHAIN_NOT_FOUND"
        out["FragmentInterfaceClass"] = "NA"
        out["parser_file"] = used_path
        out["chain_used"] = "NA"
        out["chain_id_mode"] = chain_id_mode
        out["warn"] = "CHAIN_NOT_FOUND"
        out["rand_samples"] = RAND_SAMPLES
        out["rand_mean_interface_frac"] = np.nan
        out["rand_std_interface_frac"] = np.nan
        out["interface_fraction_real"] = np.nan
        out["rand_zscore"] = np.nan
        out["rand_pvalue_ge"] = np.nan
        out["rand_enrichment"] = np.nan
        return main_hmm, out, f"[{main_hmm}] CHAIN_NOT_FOUND pdb={pdb_id} file={used_path}"

    _, chain_used, struct_seq, struct_keys, struct_residues = best
    N = len(struct_keys)

    # mapping: fasta_pos -> struct_index (0-based)
    map_pos_to_idx = align_map_fasta_to_struct_index(aligner, fasta_seq, struct_seq)

    # build interface set
    if n_prot < 2:
        assembly_class = "MonomerOnly"
        ns = None
    else:
        assembly_class = "MultiChain"
        ns = build_neighbor_search_other_atoms(model, chain_used)

    interface_flags = np.zeros(N, dtype=np.int32)
    if ns is not None:
        for i, (res, key) in enumerate(zip(struct_residues, struct_keys)):
            if residue_is_interface(res, ns, DIST_CUTOFF):
                interface_flags[i] = 1

    # prefix sum for fast window counts
    prefix = np.zeros(N + 1, dtype=np.int32)
    prefix[1:] = np.cumsum(interface_flags)

    contact_res_count_chain = int(interface_flags.sum())

    # prepare output
    out = sub_df.copy()

    seg_start_list, seg_end_list, seg_len_list = [], [], []
    n_mapped_list, mapped_frac_list = [], []
    n_int_list, int_frac_list, int_frac_mapped_list = [], [], []
    cls_list, warn_list = [], []

    # random columns
    rand_mu_list, rand_sd_list = [], []
    f_real_list = []
    rand_z_list, rand_p_list, rand_enrich_list = [], [], []

    for seg in out["Main_Segment"].astype(str).tolist():
        s, e = parse_segment(seg)
        seg_len = e - s + 1

        # mapped indices (0-based) for this segment (only positions that map)
        mapped_idx = [map_pos_to_idx[pos] for pos in range(s, e + 1) if pos in map_pos_to_idx]
        n_mapped = len(mapped_idx)
        mapped_frac = (n_mapped / seg_len) if seg_len > 0 else 0.0

        # interface counts among mapped positions (not requiring contiguity)
        n_int = int(np.sum(interface_flags[mapped_idx])) if n_mapped > 0 else 0

        # original v2-style fractions:
        int_frac = (n_int / seg_len) if seg_len > 0 else 0.0
        int_frac_mapped = (n_int / n_mapped) if n_mapped > 0 else np.nan

        # ---------- Random control (Method B) ----------
        # We need a continuous window length on structure chain.
        # Use L = seg_len (FASTA length) for strict same-length control.
        # But if mapping is poor, still compute random baseline; real f uses mapped positions:
        # define f_real as interface fraction among mapped positions (same as int_frac_mapped)
        f_real = float(int_frac_mapped) if not np.isnan(int_frac_mapped) else np.nan

        if np.isnan(f_real):
            mu = sd = z = p_ge = enrich = np.nan
        else:
            mu, sd, z, p_ge, enrich = random_control_stats(prefix, N, seg_len, f_real, rng)

        # ---------- classification ----------
        warn = ""
        if n_prot < 2:
            cls = "NonInterface"  # no other chains in file
        else:
            if mapped_frac < MIN_MAP_FRAC_WARN:
                cls = "LOW_MAP"
                warn = f"LOW_MAP({mapped_frac:.2f})"
            else:
                if np.isnan(int_frac_mapped):
                    cls = "NA"
                    warn = "NO_MAPPED_RES"
                elif int_frac_mapped >= TH_MAJOR:
                    cls = "InterfaceMajor"
                elif int_frac_mapped >= TH_PARTIAL:
                    cls = "InterfacePartial"
                else:
                    cls = "NonInterface"

        seg_start_list.append(s)
        seg_end_list.append(e)
        seg_len_list.append(seg_len)

        n_mapped_list.append(n_mapped)
        mapped_frac_list.append(mapped_frac)

        n_int_list.append(n_int)
        int_frac_list.append(int_frac)
        int_frac_mapped_list.append(int_frac_mapped)

        cls_list.append(cls)
        warn_list.append(warn)

        # random lists
        rand_mu_list.append(mu)
        rand_sd_list.append(sd)
        f_real_list.append(f_real)
        rand_z_list.append(z)
        rand_p_list.append(p_ge)
        rand_enrich_list.append(enrich)

    # attach columns (keep your v2)
    out["pdb_id"] = pdb_id
    out["chain_used"] = chain_used
    out["n_protein_chains"] = n_prot
    out["AssemblyNeedSymGen"] = need_symgen
    out["oligomeric_count_annot"] = olig_count
    out["AssemblyClass"] = assembly_class
    out["contact_res_count_chain"] = contact_res_count_chain

    out["seg_start"] = seg_start_list
    out["seg_end"] = seg_end_list
    out["seg_len"] = seg_len_list

    out["n_mapped"] = n_mapped_list
    out["mapped_fraction"] = mapped_frac_list

    out["n_interface"] = n_int_list
    out["interface_fraction"] = int_frac_list
    out["interface_fraction_mapped"] = int_frac_mapped_list
    out["FragmentInterfaceClass"] = cls_list

    out["parser_file"] = used_path
    out["chain_id_mode"] = chain_id_mode
    out["warn"] = warn_list

    # random control columns
    out["rand_samples"] = RAND_SAMPLES
    out["rand_mean_interface_frac"] = rand_mu_list
    out["rand_std_interface_frac"] = rand_sd_list
    out["interface_fraction_real"] = f_real_list
    out["rand_zscore"] = rand_z_list
    out["rand_pvalue_ge"] = rand_p_list
    out["rand_enrichment"] = rand_enrich_list

    msg = (f"[{main_hmm}] OK pdb={pdb_id} chain={chain_used} "
           f"nProtChains={n_prot} contactRes(chain)={contact_res_count_chain} "
           f"needSymGen={need_symgen} file={used_path}")
    return main_hmm, out, msg


