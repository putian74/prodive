def parse_segment(seg: str) -> Tuple[int, int]:
    m = re.match(r"^\s*(\d+)\s*-\s*(\d+)\s*$", str(seg))
    if not m:
        raise ValueError(f"Bad segment format: {seg}")
    a, b = int(m.group(1)), int(m.group(2))
    if a > b:
        a, b = b, a
    return a, b


def main_hmm_to_pdbid(main_hmm: str) -> str:
    return str(main_hmm).strip().split("_")[0].upper()


def find_structure_file(pdb_id: str, struct_dir: str) -> Tuple[Optional[str], Optional[str]]:
    pdb_id_u = pdb_id.upper()
    pdb_id_l = pdb_id.lower()

    cif_candidates = [
        os.path.join(struct_dir, f"{pdb_id_u}.cif"),
        os.path.join(struct_dir, f"{pdb_id_l}.cif"),
        os.path.join(struct_dir, f"{pdb_id_u}.mmcif"),
        os.path.join(struct_dir, f"{pdb_id_l}.mmcif"),
    ]
    pdb_candidates = [
        os.path.join(struct_dir, f"{pdb_id_u}.pdb"),
        os.path.join(struct_dir, f"{pdb_id_l}.pdb"),
    ]

    cif_path = next((p for p in cif_candidates if os.path.exists(p)), None)
    pdb_path = next((p for p in pdb_candidates if os.path.exists(p)), None)
    return cif_path, pdb_path


def load_fasta_dict(fasta_path: str) -> Dict[str, Tuple[str, str]]:
    d = {}
    for rec in SeqIO.parse(fasta_path, "fasta"):
        desc = rec.description
        first = desc.split()[0]
        base = first.split("|")[0]  # '9D01_1'
        d[base] = (str(rec.seq), desc)
    return d


def extract_chain_candidates_from_desc(desc: str) -> List[str]:
    m = re.search(r"\|Chains?\s+([^|]+)\|", desc)
    if not m:
        return []
    txt = m.group(1).strip()

    auth_chain = None
    m2 = re.search(r"\[auth\s+([A-Za-z0-9]+)\]", txt)
    if m2:
        auth_chain = m2.group(1).strip()

    txt_clean = re.sub(r"\[.*?\]", "", txt).strip()
    parts = [p.strip() for p in txt_clean.split(",") if p.strip()]

    chains = []
    for p in parts:
        tok = p.split()[0].strip()
        if tok:
            chains.append(tok)

    if auth_chain:
        if auth_chain in chains:
            chains.remove(auth_chain)
        chains = [auth_chain] + chains

    out = []
    seen = set()
    for c in chains:
        if c not in seen:
            seen.add(c)
            out.append(c)
    return out


def safe_three_to_one(resname: str) -> str:
    try:
        r = resname.strip().upper()
        if r == "MSE":
            return "M"
        if r == "SEC":
            return "U"
        if r == "PYL":
            return "O"
        aa = seq1(r)  # unknown -> X
        return aa if aa and len(aa) == 1 else "X"
    except Exception:
        return "X"


def get_chain_std_residues_and_seq(chain):
    residues = []
    seq_chars = []
    keys = []
    cid = chain.id
    for res in chain:
        if not is_aa(res, standard=True):
            continue
        if "CA" not in res:
            continue
        residues.append(res)
        seq_chars.append(safe_three_to_one(res.resname))
        keys.append((cid, res.id))
    return residues, "".join(seq_chars), keys


def list_protein_chains(model):
    out = []
    for ch in model:
        residues, seq, keys = get_chain_std_residues_and_seq(ch)
        if len(residues) >= MIN_STD_AA_PER_CHAIN:
            out.append(ch)
    return out


def build_aligner() -> PairwiseAligner:
    aligner = PairwiseAligner()
    aligner.mode = "global"
    aligner.match_score = MATCH
    aligner.mismatch_score = MISMATCH
    aligner.open_gap_score = GAP_OPEN
    aligner.extend_gap_score = GAP_EXT
    return aligner


def global_align_score(aligner: PairwiseAligner, a: str, b: str) -> Optional[float]:
    alns = aligner.align(a, b)
    if len(alns) == 0:
        return None
    return float(alns[0].score)


def align_map_fasta_to_struct_index(aligner: PairwiseAligner, fasta_seq: str, struct_seq: str):
    """
    Return mapping: fasta_pos (1-based) -> struct_index (0-based position in struct_seq/struct_keys)
    """
    alns = aligner.align(fasta_seq, struct_seq)
    if len(alns) == 0:
        return {}
    aln = alns[0]
    a_blocks = aln.aligned[0]
    b_blocks = aln.aligned[1]

    mapping = {}
    for (a0, a1), (b0, b1) in zip(a_blocks, b_blocks):
        L = min(a1 - a0, b1 - b0)
        for k in range(L):
            fa_pos = (a0 + k) + 1        # 1-based
            st_idx = (b0 + k)            # 0-based
            mapping[fa_pos] = st_idx
    return mapping


def parse_structure_prefer_cif(cif_path: Optional[str], pdb_path: Optional[str]):
    if cif_path:
        try:
            parser = MMCIFParser(QUIET=True, auth_chains=True, auth_residues=True)
        except TypeError:
            parser = MMCIFParser(QUIET=True)
        st = parser.get_structure("X", cif_path)
        return st, cif_path, "mmcif_auth"
    if pdb_path:
        parser = PDBParser(QUIET=True)
        st = parser.get_structure("X", pdb_path)
        return st, pdb_path, "pdb"
    return None, None, "NA"


def parse_structure_mmcif_label(cif_path: str):
    try:
        parser = MMCIFParser(QUIET=True, auth_chains=False, auth_residues=False)
    except TypeError:
        parser = MMCIFParser(QUIET=True)
    st = parser.get_structure("X", cif_path)
    return st


def cif_assembly_need_symgen(cif_path: str) -> Tuple[str, str]:
    try:
        d = MMCIF2Dict(cif_path)
        counts = d.get("_pdbx_struct_assembly.oligomeric_count", None)
        olig_count = "NA" if counts is None else (str(counts[0]) if isinstance(counts, list) else str(counts))

        opers = d.get("_pdbx_struct_assembly_gen.oper_expression", None)
        if opers is None:
            return olig_count, "unknown"

        ops = [str(x).strip() for x in opers] if isinstance(opers, list) else [str(opers).strip()]
        for op in ops:
            if op != "1":
                return olig_count, "yes"
        return olig_count, "no"
    except Exception:
        return "NA", "unknown"


def build_neighbor_search_other_atoms(model, target_chain_id: str):
    atoms = []
    for ch in model:
        if ch.id == target_chain_id:
            continue
        residues, seq, keys = get_chain_std_residues_and_seq(ch)
        if len(residues) < MIN_STD_AA_PER_CHAIN:
            continue
        for res in residues:
            for atom in res.get_atoms():
                elem = getattr(atom, "element", "").strip()
                name = atom.get_name()
                if elem == "H" or name.startswith("H"):
                    continue
                atoms.append(atom)
    if not atoms:
        return None
    return NeighborSearch(atoms)


def residue_is_interface(residue, ns: NeighborSearch, cutoff: float) -> bool:
    if ns is None:
        return False
    for atom in residue.get_atoms():
        elem = getattr(atom, "element", "").strip()
        name = atom.get_name()
        if elem == "H" or name.startswith("H"):
            continue
        if ns.search(atom.coord, cutoff, level="A"):
            return True
    return False


def random_control_stats(prefix_iface: np.ndarray, N: int, L: int, f_real: float, rng: np.random.Generator):
    """
    prefix_iface: prefix sum of interface flags length N+1, prefix_iface[0]=0
    N: chain length (number of residues used in struct_seq/keys)
    L: window length
    f_real: real interface fraction in [0,1]
    """
    if L <= 0 or L > N:
        return (np.nan, np.nan, np.nan, np.nan, np.nan)

    # sample starts uniformly in [0, N-L]
    starts = rng.integers(0, N - L + 1, size=RAND_SAMPLES, endpoint=False)
    # window interface counts by prefix sum
    cnt = prefix_iface[starts + L] - prefix_iface[starts]
    vals = cnt / float(L)

    mu = float(vals.mean())
    sigma = float(vals.std(ddof=0))

    # right-tail p: P(rand >= real)
    ge = int(np.sum(vals >= f_real))
    p_ge = (ge + 1) / (RAND_SAMPLES + 1)

    # z-score
    z = (f_real - mu) / sigma if sigma > 0 else 0.0

    # enrichment
    enrich = (f_real / mu) if mu > 0 else (np.inf if f_real > 0 else 0.0)

    return (mu, sigma, z, p_ge, enrich)


